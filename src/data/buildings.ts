/** Every definition, keyed by id. */
export const BUILDING_DEFS: Record<string, BuildingDef> = Object.fromEntries(
  [...DWELLINGS, ...SHOPS, ...INDUSTRY, ...SERVICES, ...TRADE_HUBS].map((def) => [def.id, def]),
);

export const ALL_BUILDING_DEFS: readonly BuildingDef[] = Object.values(BUILDING_DEFS);

export function getDef(id: string): BuildingDef {
  const def = BUILDING_DEFS[id];
  if (!def) throw new Error(`Unknown building definition: ${id}`);
  return def;
}

/** Definitions the player can place directly, in menu order. */
export const PLACEABLE_DEFS: readonly BuildingDef[] = [...SERVICES, ...TRADE_HUBS];

/** Growth ladder for a zone, ordered by level. */
export function growthLadder(zone: Zone, line: IndustryLine = 'farm'): BuildingDef[] {
  switch (zone) {
    case Zone.Residential:
      return DWELLINGS;
    case Zone.Commercial:
      return SHOPS;
    case Zone.Industrial:
      return INDUSTRY_LINES[line].map(getDef);
    default:
      return [];
  }
}

/** Highest level available in a zone's ladder. */
export function maxLevel(zone: Zone, line: IndustryLine = 'farm'): number {
  return growthLadder(zone, line).length;
}
